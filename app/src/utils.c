// Map an ASCII character to its bitmap glyph.
static const unsigned char* glyph_for_5x7(char c)
{
    if (c >= 'A' && c <= 'Z') c = (char)(c - 'A' + 'a');
    if (c == ' ') return font_5x7[0];
    if (c >= '0' && c <= '9') return font_5x7[1 + (c - '0')];
    if (c >= 'a' && c <= 'z') return font_5x7[11 + (c - 'a')];
    switch (c) {
    case ':': return font_5x7[11 + 26];
    case '#': return font_5x7[11 + 27];
    case '(': return font_5x7[11 + 28];
    case ')': return font_5x7[11 + 29];
    case '-': return font_5x7[11 + 30];
    default:  return font_5x7[0];
    }
}

// Draw bitmap text in 2D screen space.
void draw_text_2d(int window_w, int window_h, int x_px, int y_px, const char* text)
{
    if (text == NULL || text[0] == '\0') return;

    // Render HUD text using top-left screen coordinates.
    const int SCALE = 2;

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrtho(0, window_w, 0, window_h, -1, 1);

    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();

    glDisable(GL_LIGHTING);
    glDisable(GL_TEXTURE_2D);
    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glColor4f(1.f, 1.f, 1.f, 1.f);
    glPointSize((GLfloat)SCALE);

    int x = x_px;
    int y = window_h - y_px - (7 * SCALE);

    glBegin(GL_POINTS);
    for (const char* p = text; *p; ++p) {
        if (*p == '\n') {
            x = x_px;
            y -= 9 * SCALE;
            continue;
        }
        const unsigned char* g = glyph_for_5x7(*p);
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if ((g[row] >> (4 - col)) & 1) {
                    glVertex2i(x + col * SCALE, y + (6 - row) * SCALE);
                }
            }
        }
        x += 6 * SCALE;
    }
    glEnd();

    glPointSize(1.f);
    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);

    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
    glMatrixMode(GL_MODELVIEW);
}

// Draw a filled 2D rectangle for simple UI panels.
void draw_filled_rect_2d(int window_w, int window_h,
                         int x_px, int y_px, int w_px, int h_px,
                         float r, float g, float b, float a)
{
    // Interpret rectangle coordinates from the top-left corner.
    int x0 = x_px;
    int y0 = window_h - y_px - h_px;
    int x1 = x0 + w_px;
    int y1 = y0 + h_px;

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrtho(0, window_w, 0, window_h, -1, 1);

    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();

    glDisable(GL_LIGHTING);
    glDisable(GL_TEXTURE_2D);
    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);
    glColor4f(r, g, b, a);

    glBegin(GL_QUADS);
    glVertex2i(x0, y0);
    glVertex2i(x1, y0);
    glVertex2i(x1, y1);
    glVertex2i(x0, y1);
    glEnd();

    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);

    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
    glMatrixMode(GL_MODELVIEW);
}

